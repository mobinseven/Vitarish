using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Options;
using Vorn.Caas.Host.Infrastructure.Services;
using Vorn.Caas.Host.Presentation.HealthChecks;
using Vorn.Caas.Messages.Domain.Interfaces;
using Vorn.Caas.Messages.Infrastructure.Services;
using Vorn.Caas.Messages.Infrastructure.Wrappers.SmsDotIr;
using VornOptions = Vorn.Caas.Messages.Domain.Options.VornOptions;

WebApplicationBuilder builder = WebApplication.CreateBuilder(args);
IConfigurationSection section = builder.Configuration.GetSection(VornOptions.Section);
builder.Services.Configure<VornOptions>(section);
builder.Services.AddSingleton<VornOptions>(sp => sp.GetRequiredService<IOptions<VornOptions>>().Value);
builder.Services.AddTransient<IMessagesService, MessagesService>();
builder.Services.AddTransient<ISmsProvider, SmsDotIrProvider>();
builder.Services.AddHostedService<AaasHealthMonitorService>();
builder.Services.ConfigureAaasClient(builder.Configuration);
builder.AddDashboardServices();
WebApplication app = builder.Build();
app.UseDashboardServices();
app.UseStartupSmsTest();
app.UseAuthentication();
app.UseAuthorization();
app.MapMessagesEndpoints();
app.MapGet("/", () => "Vorn CaaS Service is running.");
app.Run();

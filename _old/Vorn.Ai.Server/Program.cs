using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.AspNetCore.SignalR;
using Vorn.Aaas.Client.Api.HubFilter;
using Vorn.Ai.Server.Domain.Options;
using Vorn.Ai.Server.Infrastructure.Services.OpenAi;
using Vorn.Ai.Server.Presentation.Hub;

WebApplicationBuilder builder = WebApplication.CreateBuilder(args);
VornOptions vornOptions = new();
IConfigurationSection section = builder.Configuration.GetSection(VornOptions.Section);
section.Bind(vornOptions);
builder.Services.AddSingleton(vornOptions);
builder.Services.AddTransient<IResponder, Responder>();
builder.Services.AddTransient<IAudioTranscriber, AudioTranscriber>();
builder.Services.ConfigureAaasClient(builder.Configuration);
builder.Services.AddAntiforgery();
builder.Services.AddSignalR(o => o.AddFilter<RequestIdentityContextHubFilter>()).AddMessagePackProtocol();
builder.AddDashboardServices();
WebApplication app = builder.Build();
app.UseDashboardServices();
app.UseAuthentication();
app.UseAuthorization();
app.MapHub<ResponseHub>("/ai/hubs/response");
app.MapHub<SpeechHub>("/ai/hubs/speech");
app.MapGet("/", () => "Vorn AI Service is running.");
app.Run();

using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.Extensions.Options;
using System.Text;
using Vitarish.Calendar.Infrastructure.Data;
using Vitarish.Calendar.Infrastructure.Helpers;
using Vitarish.Calendar.Infrastructure.Options;
using Vitarish.Entities.Server.Extensions;

namespace Vitarish.Calendar.Infrastructure.DependencyInjection;

public static class DependencyInjectionExtensions
{
    public static IServiceCollection AddCalendarInfrastructure(
        this IServiceCollection services,
        Action<DbContextOptionsBuilder>? configureDbContext = null)
    {
        // Injectio-generated registration for all [RegisterTransient] services in this assembly
        _ = services.AddVitarishCalendarInfrastructure();

        // MediatR scan for entity pipeline handlers generated by the source generator
        _ = services.AddMediatR(cfg => cfg.RegisterServicesFromAssembly(typeof(CalendarDbContext).Assembly));

        // Named HTTP client for Radicale
        _ = services.AddHttpClient("Radicale", (provider, client) =>
        {
            RadicaleOptions opts = provider.GetRequiredService<IOptions<RadicaleOptions>>().Value;

            if (!string.IsNullOrEmpty(opts.BaseUrl))
            {
                client.BaseAddress = new Uri(opts.BaseUrl);
            }

            client.Timeout = TimeSpan.FromSeconds(opts.TimeoutSeconds > 0 ? opts.TimeoutSeconds : 30);

            if (opts.AuthScheme == RadicaleAuthScheme.Basic
                && !string.IsNullOrEmpty(opts.Username))
            {
                string credentials = Convert.ToBase64String(
                    Encoding.UTF8.GetBytes($"{opts.Username}:{opts.Password}"));
                client.DefaultRequestHeaders.Authorization =
                    new System.Net.Http.Headers.AuthenticationHeaderValue("Basic", credentials);
            }
            else if (opts.AuthScheme == RadicaleAuthScheme.BearerToken
                && !string.IsNullOrEmpty(opts.Password))
            {
                client.DefaultRequestHeaders.Authorization =
                    new System.Net.Http.Headers.AuthenticationHeaderValue("Bearer", opts.Password);
            }
        });

        // DbContext
        _ = services.AddTransientMultiTenantDbContext<CalendarDbContext>((_, options) => configureDbContext?.Invoke(options));

        return services;
    }
}
